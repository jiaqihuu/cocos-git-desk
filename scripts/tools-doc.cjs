#!/usr/bin/env node
// Generates docs/TOOLS.md from the MCP tool catalogue in static/.
//
// Reads static/mcp-tools.<group>.json when the split catalogue exists (core, inspector, bridge, i18n),
// otherwise falls back to the single static/mcp-tools.json and assigns groups by tool name.
//
//   node scripts/tools-doc.cjs            # rewrite docs/TOOLS.md
//   node scripts/tools-doc.cjs --check    # exit 1 when docs/TOOLS.md is out of date
//   node scripts/tools-doc.cjs --out -    # print to stdout
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const staticDir = path.join(root, 'static');
const GROUPS = ['core', 'inspector', 'bridge', 'i18n'];
const GROUP_TITLES = {
    core: 'Core (Git MCP and editor tools)',
    inspector: 'Runtime inspector and page event capture',
    bridge: 'Project preview bridge',
    i18n: 'Language key audit',
};
const GROUP_NOTES = {
    core: 'Always available. `git_desk_*` tools talk to the Git service; `creator_*` tools call Creator asset-db, scene and preview messages directly.',
    inspector: 'Needs the embedded Debug Preview panel open in Creator. Uses only the Chrome DevTools Protocol of the embedded preview; no project code is required.',
    bridge: 'Needs the project to inject a preview bridge script that implements the bridge interface (`bridge.*` in `git-desk.config.json`). Tools are listed only when the bridge is enabled.',
    i18n: 'Enabled only when `i18n.keyPattern` is configured in `git-desk.config.json`.',
};
// Fallback grouping for the unsplit catalogue (static/mcp-tools.json).
const INSPECTOR_BROWSER_DEBUG = new Set(['start', 'status', 'events', 'summary', 'mark', 'wait_for_reload', 'compare', 'stop', 'export'].map(s => 'browser_debug_' + s));

function groupOf(name) {
    if (name === 'creator_language_keys') return 'i18n';
    if (name.startsWith('git_desk_') || name.startsWith('creator_')) return 'core';
    if (name.startsWith('runtime_inspector_')) return 'inspector';
    if (name.startsWith('browser_debug_')) return INSPECTOR_BROWSER_DEBUG.has(name) ? 'inspector' : 'bridge';
    return 'core';
}

function loadCatalogue() {
    const split = GROUPS.map(group => ({ group, file: path.join(staticDir, `mcp-tools.${group}.json`) })).filter(item => fs.existsSync(item.file));
    const tools = [];
    if (split.length) {
        for (const { group, file } of split) for (const tool of JSON.parse(fs.readFileSync(file, 'utf8'))) tools.push({ ...tool, group, source: path.basename(file) });
        return { tools, sources: split.map(item => path.basename(item.file)) };
    }
    const file = path.join(staticDir, 'mcp-tools.json');
    for (const tool of JSON.parse(fs.readFileSync(file, 'utf8'))) tools.push({ ...tool, group: groupOf(tool.name), source: 'mcp-tools.json' });
    return { tools, sources: ['mcp-tools.json'] };
}

function firstSentence(text) {
    const clean = String(text || '').replace(/\s+/g, ' ').trim();
    const match = clean.match(/^(.*?[.!?])(?:\s|$)/);
    return (match ? match[1] : clean).trim();
}

function cell(text) { return String(text).replace(/\|/g, '\\|').replace(/\n/g, ' '); }
function slug(title) { return title.toLowerCase().replace(/[^a-z0-9\s-]/g, '').trim().replace(/\s+/g, '-'); }
function requirement(group) { return GROUP_NOTES[group].split('. ')[0].replace(/\.$/, '') + '.'; }

function parameterSummary(schema) {
    const properties = (schema && schema.properties) || {};
    const required = new Set((schema && schema.required) || []);
    const parts = Object.keys(properties).map(key => {
        const property = properties[key] || {};
        let detail = '';
        if (Array.isArray(property.enum) && property.enum.length <= 6) detail = '=' + property.enum.join('|');
        else if (Array.isArray(property.enum)) detail = '=' + property.enum.slice(0, 4).join('|') + '|…';
        else if (property.type && property.type !== 'string') detail = ':' + (Array.isArray(property.type) ? property.type.join('|') : property.type);
        return '`' + key + (required.has(key) ? '' : '?') + detail + '`';
    });
    return parts.length ? parts.join(', ') : '—';
}

function access(tool) {
    const annotations = tool.annotations || {};
    if (annotations.readOnlyHint === true) return 'read';
    return annotations.destructiveHint === true ? 'write (destructive)' : 'write';
}

function render({ tools, sources }) {
    const lines = [];
    lines.push('# Tool catalogue');
    lines.push('');
    lines.push(`Generated by \`node scripts/tools-doc.cjs\` from ${sources.map(s => '`static/' + s + '`').join(', ')}. Do not edit by hand.`);
    lines.push('');
    lines.push(`${tools.length} tools. "Access" comes from the MCP \`annotations\` (\`readOnlyHint\`, \`destructiveHint\`). Parameters: \`name\` is required, \`name?\` optional; \`=a|b\` lists an enum, \`:type\` a non-string type. Every \`git_desk_*\` tool also accepts \`context?\` (default \`creator\`) to address an isolated worktree context. Full schemas live in the JSON files; usage rules are in [AGENT_API.md](AGENT_API.md).`);
    lines.push('');
    lines.push('| Group | Tools | Requires |');
    lines.push('| --- | ---: | --- |');
    for (const group of GROUPS) {
        const count = tools.filter(t => t.group === group).length;
        if (!count) continue;
        lines.push(`| [${GROUP_TITLES[group]}](#${slug(GROUP_TITLES[group])}) | ${count} | ${cell(requirement(group))} |`);
    }
    for (const group of GROUPS) {
        const members = tools.filter(t => t.group === group);
        if (!members.length) continue;
        lines.push('');
        lines.push(`## ${GROUP_TITLES[group]}`);
        lines.push('');
        lines.push(GROUP_NOTES[group]);
        lines.push('');
        lines.push('| Tool | Access | Parameters | Description |');
        lines.push('| --- | --- | --- | --- |');
        for (const tool of members) lines.push(`| \`${tool.name}\` | ${access(tool)} | ${cell(parameterSummary(tool.inputSchema))} | ${cell(firstSentence(tool.description))} |`);
    }
    lines.push('');
    return lines.join('\n');
}

function main(argv) {
    const check = argv.includes('--check');
    const outIndex = argv.indexOf('--out');
    const out = outIndex >= 0 ? argv[outIndex + 1] : path.join(root, 'docs', 'TOOLS.md');
    const content = render(loadCatalogue());
    if (out === '-') { process.stdout.write(content); return 0; }
    if (check) {
        const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
        if (current !== content) { console.error(`${path.relative(root, out)} is out of date; run: node scripts/tools-doc.cjs`); return 1; }
        console.log(`${path.relative(root, out)} is up to date.`);
        return 0;
    }
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, content);
    console.log(`${path.relative(root, out)}: ${content.split('\n').filter(l => l.startsWith('| `')).length} tools`);
    return 0;
}

if (require.main === module) process.exit(main(process.argv.slice(2)));
module.exports = { loadCatalogue, render, groupOf };
